import {
  Document,
  HeadingLevel,
  Packer,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
} from 'docx';
import { domainRows, elementLabel, elementTypeLabel, metadataRows, workspaceName } from './report-data';
import { primaryText, type ArchiElement, type Model, type Relationship, type View } from '@openarch/core';

function table(headers: string[], rows: string[][]): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        children: headers.map(
          (header) =>
            new TableCell({
              children: [new Paragraph({ children: [new TextRun({ text: header, bold: true })] })],
            }),
        ),
      }),
      ...rows.map(
        (row) =>
          new TableRow({
            children: row.map(
              (cell) => new TableCell({ children: [new Paragraph({ children: [new TextRun(cell)] })] }),
            ),
          }),
      ),
    ],
  });
}

/** Render a workspace as a Word document: metadata, domains, elements, relationships, views, artefacts. */
export async function exportWorkspaceDocx(model: Model): Promise<Uint8Array> {
  const name = workspaceName(model);
  const sections = [
    new Paragraph({ text: name, heading: HeadingLevel.TITLE }),
    new Paragraph({
      children: [
        new TextRun({
          text: `Generated by OpenArch · ${new Date().toISOString().slice(0, 10)} · ${model.elements.length} elements · ${model.relationships.length} relationships · ${model.views.length} views`,
          italics: true,
        }),
      ],
    }),
    new Paragraph({ text: 'Metadata', heading: HeadingLevel.HEADING_1 }),
    table(['Field', 'Value'], metadataRows(model)),
    new Paragraph({ text: 'Domains', heading: HeadingLevel.HEADING_1 }),
    table(['Domain', 'Owner', 'Elements', 'Relationships', 'Cross-domain'], domainRows(model)),
    new Paragraph({ text: 'Elements', heading: HeadingLevel.HEADING_1 }),
    table(
      ['Name', 'Type', 'Domain', 'Environment'],
      model.elements.map((element: ArchiElement) => [
        elementLabel(element, element.id),
        elementTypeLabel(element.type),
        element.domain ?? '—',
        element.environment ?? '—',
      ]),
    ),
    new Paragraph({ text: 'Relationships', heading: HeadingLevel.HEADING_1 }),
    table(
      ['Type', 'Source', 'Target', 'Name'],
      model.relationships.map((relationship: Relationship) => [
        relationship.type,
        elementLabel(model.elements.find((element: ArchiElement) => element.id === relationship.source), relationship.source),
        elementLabel(model.elements.find((element: ArchiElement) => element.id === relationship.target), relationship.target),
        primaryText(relationship.name),
      ]),
    ),
    new Paragraph({ text: 'Views', heading: HeadingLevel.HEADING_1 }),
    ...model.views.map(
      (view: View) =>
        new Paragraph({
          children: [
            new TextRun({ text: `${primaryText(view.name) || view.id} — ${view.nodes.length} nodes, ${view.edges.length} edges`, bold: true }),
          ],
        }),
    ),
  ];

  for (const artefact of model.artefacts ?? []) {
    sections.push(new Paragraph({ text: `${artefact.kind.toUpperCase()}: ${artefact.title}`, heading: HeadingLevel.HEADING_2 }));
    sections.push(new Paragraph({ text: artefact.body || '(no body)' }));
  }

  const doc = new Document({
    sections: [{ children: sections, properties: {} }],
  });
  return Packer.pack(doc, 'uint8array') as Promise<Uint8Array>;
}

export function docxMime(): string {
  return 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
}
